//! Gate de drift de contratos v2 executável só com Rust (sem node/pnpm).
//!
//! O job `schema-drift` do CI só detecta JSON Schema desatualizado depois de
//! instalar pnpm + codegen TypeScript. Enquanto isso, `cargo test --workspace`
//! passava com `contracts/v2/schemas/` defasado. Este teste fecha esse buraco:
//! roda o binário `export-schemas` em um diretório temporário e compara
//! **byte a byte** com os arquivos versionados, falhando em qualquer divergência.
//!
//! Cobre o diretório inteiro: além de `contracts/v2/schemas/*.schema.json`, compara
//! também `contracts/v2/manifest.json` e `contracts/v2/version.lock`, que saem da
//! mesma execução (o `version.lock` carrega o sha256 do conjunto de schemas, então
//! qualquer byte defasado muda o digest e aparece aqui).

use std::collections::BTreeSet;
use std::fs;
use std::path::{Path, PathBuf};
use std::process::Command;

/// Artefatos que o `export-schemas` escreve ao lado de `schemas/`, na raiz do contrato v2.
const AUX_FILES: [&str; 2] = ["manifest.json", "version.lock"];

/// Diretório versionado do contrato v2 (`contracts/v2/`).
fn committed_v2_dir() -> PathBuf {
    Path::new(env!("CARGO_MANIFEST_DIR"))
        .join("..")
        .join("..")
        .join("contracts")
        .join("v2")
}

/// Diretório versionado dos JSON Schemas v2 (`contracts/v2/schemas/`).
fn committed_schema_dir() -> PathBuf {
    committed_v2_dir().join("schemas")
}

/// Descreve a primeira diferença entre dois arquivos, para mensagens acionáveis.
fn describe_difference(generated_bytes: &[u8], committed_bytes: &[u8]) -> String {
    let generated_text = String::from_utf8_lossy(generated_bytes);
    let committed_text = String::from_utf8_lossy(committed_bytes);
    generated_text
        .lines()
        .zip(committed_text.lines())
        .enumerate()
        .find(|(_, (generated_line, committed_line))| generated_line != committed_line)
        .map_or_else(
            || {
                format!(
                    "identical {{content}} up to the shorter file (len {} vs {} bytes)",
                    generated_bytes.len(),
                    committed_bytes.len()
                )
            },
            |(index, (generated_line, committed_line))| {
                format!(
                    "first difference at line {}:\n  generated: {generated_line}\n  committed: {committed_line}",
                    index + 1
                )
            },
        )
}

/// Compara byte a byte um arquivo gerado com o versionado.
fn compare_single_file(generated: &Path, committed: &Path, label: &str) -> Option<String> {
    let generated_bytes = fs::read(generated)
        .unwrap_or_else(|err| panic!("failed to read {}: {err}", generated.display()));
    let committed_bytes = fs::read(committed)
        .unwrap_or_else(|err| panic!("failed to read {}: {err}", committed.display()));
    if generated_bytes == committed_bytes {
        return None;
    }
    Some(format!(
        "byte drift in {label}: {}",
        describe_difference(&generated_bytes, &committed_bytes)
    ))
}

/// Compara `manifest.json` e `version.lock` gerados com os versionados.
fn compare_aux_files(generated_v2: &Path, committed_v2: &Path) -> Vec<String> {
    let mut problems = Vec::new();
    for name in AUX_FILES {
        let generated = generated_v2.join(name);
        let committed = committed_v2.join(name);
        match (generated.exists(), committed.exists()) {
            (true, false) => {
                problems.push(format!(
                    "missing in contracts/v2: {name} (generated by export-schemas)"
                ));
                continue;
            }
            (false, true) => {
                problems.push(format!(
                    "stale file in contracts/v2: {name} (no longer generated)"
                ));
                continue;
            }
            (false, false) => continue,
            (true, true) => {}
        }
        if let Some(problem) =
            compare_single_file(&generated, &committed, &format!("contracts/v2/{name}"))
        {
            problems.push(problem);
        }
    }
    problems
}

/// Lista os `*.schema.json` de um diretório, ordenados.
fn schema_file_names(dir: &Path) -> Vec<String> {
    let mut names: Vec<String> = match fs::read_dir(dir) {
        Ok(entries) => entries
            .map(|entry| entry.expect("directory entry must be readable").path())
            .filter(|path| {
                path.file_name()
                    .and_then(|name| name.to_str())
                    .is_some_and(|name| name.ends_with(".schema.json"))
            })
            .filter_map(|path| {
                path.file_name()
                    .and_then(|name| name.to_str())
                    .map(str::to_owned)
            })
            .collect(),
        Err(err) => panic!("failed to read {}: {err}", dir.display()),
    };
    names.sort();
    names
}

/// Compara o schema gerado com o commitado e devolve a lista de divergências.
fn compare_schemas(generated_dir: &Path, committed_dir: &Path) -> Vec<String> {
    let generated = schema_file_names(generated_dir);
    let committed = schema_file_names(committed_dir);

    let mut problems: Vec<String> = Vec::new();

    let generated_set: BTreeSet<&str> = generated.iter().map(String::as_str).collect();
    let committed_set: BTreeSet<&str> = committed.iter().map(String::as_str).collect();

    for missing in generated_set.difference(&committed_set) {
        problems.push(format!(
            "missing in contracts/v2/schemas: {missing} (generated by export-schemas)"
        ));
    }
    for stale in committed_set.difference(&generated_set) {
        problems.push(format!(
            "stale file in contracts/v2/schemas: {stale} (no longer generated)"
        ));
    }

    for name in generated_set.intersection(&committed_set) {
        let generated_path = generated_dir.join(name);
        let committed_path = committed_dir.join(name);
        if let Some(problem) = compare_single_file(
            &generated_path,
            &committed_path,
            &format!("contracts/v2/schemas/{name}"),
        ) {
            problems.push(problem);
        }
    }

    problems
}

/// Prova que o comparador detecta drift de verdade (byte trocado e arquivo
/// extra), sem tocar em `contracts/v2/schemas/` versionado.
#[test]
fn test_comparator_detects_byte_drift_and_stale_files() {
    let generated = tempfile::tempdir().expect("tempdir generated");
    let committed = tempfile::tempdir().expect("tempdir committed");

    let original = "{\n  \"title\": \"Sample\"\n}\n";
    fs::write(generated.path().join("sample.schema.json"), original).expect("write generated");
    fs::write(committed.path().join("sample.schema.json"), original).expect("write committed");
    fs::write(
        generated.path().join("only_generated.schema.json"),
        original,
    )
    .expect("write generated extra");
    fs::write(
        committed.path().join("only_committed.schema.json"),
        original,
    )
    .expect("write committed extra");

    let problems = compare_schemas(generated.path(), committed.path());
    let joined = problems.join("\n");
    assert!(
        joined.contains("missing in contracts/v2/schemas: only_generated.schema.json"),
        "expected missing-file problem, got: {joined}"
    );
    assert!(
        joined.contains("stale file in contracts/v2/schemas: only_committed.schema.json"),
        "expected stale-file problem, got: {joined}"
    );
    assert!(
        !joined.contains("byte drift in contracts/v2/schemas/sample.schema.json"),
        "identical files must not be reported as drift, got: {joined}"
    );

    // Troca de um único byte no arquivo commitado deve ser detectada.
    fs::write(
        committed.path().join("sample.schema.json"),
        "{\n  \"title\": \"Sample!\"\n}\n",
    )
    .expect("rewrite committed");
    let problems = compare_schemas(generated.path(), committed.path());
    let joined = problems.join("\n");
    assert!(
        joined.contains("byte drift in contracts/v2/schemas/sample.schema.json"),
        "expected byte drift problem, got: {joined}"
    );
}

#[test]
fn test_aux_comparator_detects_drift_and_missing_artifacts() {
    let generated = tempfile::tempdir().expect("tempdir generated");
    let committed = tempfile::tempdir().expect("tempdir committed");

    fs::write(generated.path().join("manifest.json"), "{\n  \"a\": 1\n}\n")
        .expect("write manifest");
    fs::write(committed.path().join("manifest.json"), "{\n  \"a\": 1\n}\n")
        .expect("write manifest");
    fs::write(generated.path().join("version.lock"), "{\n  \"d\": 1\n}\n").expect("write lock");

    let problems = compare_aux_files(generated.path(), committed.path());
    let joined = problems.join("\n");
    assert!(
        joined.contains("missing in contracts/v2: version.lock"),
        "expected missing version.lock problem, got: {joined}"
    );
    assert!(
        !joined.contains("byte drift in contracts/v2/manifest.json"),
        "identical artifacts must not be reported as drift, got: {joined}"
    );

    fs::write(committed.path().join("version.lock"), "{\n  \"d\": 1\n}\n").expect("write lock");
    fs::write(committed.path().join("manifest.json"), "{\n  \"a\": 2\n}\n")
        .expect("rewrite manifest");
    let problems = compare_aux_files(generated.path(), committed.path());
    let joined = problems.join("\n");
    assert!(
        joined.contains("byte drift in contracts/v2/manifest.json"),
        "expected byte drift for manifest.json, got: {joined}"
    );
    assert!(
        joined.contains("first difference at line 2"),
        "expected a line-level diagnosis, got: {joined}"
    );
}

#[test]
fn test_contracts_v2_schemas_match_export_schemas_output() {
    let committed_dir = committed_schema_dir();
    assert!(
        committed_dir.is_dir(),
        "committed schema directory must exist: {}",
        committed_dir.display()
    );

    let temp = tempfile::tempdir().expect("tempdir for generated schemas");
    // `--out-dir <root>/schemas` keeps `manifest.json`/`version.lock` inside the tempdir,
    // mirroring the committed layout (`contracts/v2/schemas` + `contracts/v2/{manifest,lock}`).
    let generated_schemas = temp.path().join("v2").join("schemas");
    let output = Command::new(env!("CARGO_BIN_EXE_export-schemas"))
        .arg("--out-dir")
        .arg(&generated_schemas)
        .output()
        .expect("failed to execute export-schemas");

    assert!(
        output.status.success(),
        "export-schemas must exit 0, got {:?}\nstdout: {}\nstderr: {}",
        output.status,
        String::from_utf8_lossy(&output.stdout),
        String::from_utf8_lossy(&output.stderr)
    );

    let generated = schema_file_names(&generated_schemas);
    let committed = schema_file_names(&committed_dir);
    assert!(
        !generated.is_empty(),
        "export-schemas must emit at least one *.schema.json in {}",
        generated_schemas.display()
    );

    let mut problems = compare_schemas(&generated_schemas, &committed_dir);
    problems.extend(compare_aux_files(
        &temp.path().join("v2"),
        &committed_v2_dir(),
    ));
    assert!(
        problems.is_empty(),
        "contracts/v2/ is out of date with export-schemas ({} generated, {} committed). \
         Regenerate with `cargo run -p anki-workflow-mcp --bin export-schemas`:\n{}",
        generated.len(),
        committed.len(),
        problems.join("\n")
    );
}
